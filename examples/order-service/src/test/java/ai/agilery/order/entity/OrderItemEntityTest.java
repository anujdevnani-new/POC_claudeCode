package ai.agilery.order.entity;

import java.util.UUID;

import java.lang.reflect.Field;
import java.time.LocalDateTime;
import java.util.Arrays;

import org.assertj.core.api.Assertions;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;
import org.junit.jupiter.api.Test;
import org.springframework.data.annotation.CreatedBy;
import org.springframework.data.annotation.LastModifiedBy;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

class OrderItemEntityTest {

    /**
     * Tests OrderItem entity annotations and table index configuration.
     *
     * <p>
     * Verifies that the {@link OrderItem} entity is correctly annotated with
     * {@link Entity} and {@link Table}, that Lombok {@code @Data} generates working
     * accessors, and that required database indexes are defined on the mapped
     * table.
     * </p>
     */
    @Test
    void testForAnnotationsAndTableIndexes() {

        // Verify @Entity
        Assertions.assertThat(OrderItem.class).as("OrderItem class should be annotated with @Entity")
                .hasAnnotation(Entity.class);

        // Verify Lombok @Data
        OrderItem orderItem = new OrderItem();
        orderItem.setProductName("MacBook Pro");

        Assertions.assertThat(orderItem.getProductName())
                .as("Getter and setter generated by Lombok @Data should work correctly").isEqualTo("MacBook Pro");

        // Verify @Table
        Table table = OrderItem.class.getAnnotation(Table.class);

        Assertions.assertThat(table).as("@Table annotation should be present on OrderItem entity").isNotNull();

        Assertions.assertThat(table.name()).as("Database table name should be 'order_items'").isEqualTo("order_items");

        // Verify table indexes
        Index[] indexes = table.indexes();

        Assertions.assertThat(indexes).as("OrderItem table should define exactly 2 indexes").hasSize(2);

        // Verify index on order_id column
        Assertions.assertThat(indexes).as("Index 'idx_order_item_order_id' should exist on order_id column")
                .anySatisfy(index -> {
                    Assertions.assertThat(index.name()).isEqualTo("idx_order_item_order_id");
                    Assertions.assertThat(index.columnList()).isEqualTo("order_id");
                });

        // Verify index on productSku column
        Assertions.assertThat(indexes).as("Index 'idx_order_item_product_sku' should exist on productSku column")
                .anySatisfy(index -> {
                    Assertions.assertThat(index.name()).isEqualTo("idx_order_item_product_sku");
                    Assertions.assertThat(index.columnList()).isEqualTo("product_sku");
                });
    }

    /**
     * Tests OrderItem entity primary key field annotations.
     *
     * <p>
     * Verifies that the {@link OrderItem} entity defines an {@code id} field
     * annotated with {@link Id} and {@link GeneratedValue}, and that the identifier
     * generation strategy is configured as {@link GenerationType.UUID}.
     * </p>
     */
    @Test
    void testForIdFieldAnnotations() throws Exception {

        // Retrieve the id field
        Field idField = OrderItem.class.getDeclaredField("id");

        // Verify @Id
        Assertions.assertThat(idField.isAnnotationPresent(Id.class)).as("OrderItem should have @Id on id field")
                .isTrue();

        // Verify @GeneratedValue
        Assertions.assertThat(idField.isAnnotationPresent(GeneratedValue.class))
                .as("OrderItem id should be auto-generated").isTrue();

        // Verify generation strategy
        GeneratedValue generatedValue = idField.getAnnotation(GeneratedValue.class);
        Assertions.assertThat(generatedValue.strategy()).as("ID generation strategy should be IDENTITY")
                .isEqualTo(GenerationType.UUID);
    }

    /**
     * Tests OrderItem entity column mappings and constraints.
     *
     * <p>
     * Verifies that the {@link OrderItem} entity defines expected {@link Column}
     * mappings with correct nullability, length, precision, and scale.
     * </p>
     */
    @Test
    void testForColumnMappings() throws Exception {

        // Verify total number of @Column fields
        long columnCount = Arrays.stream(OrderItem.class.getDeclaredFields())
                .filter(field -> field.isAnnotationPresent(Column.class)).count();

        Assertions.assertThat(columnCount).as("OrderItem entity should have exactly 4 @Column fields").isEqualTo(4);

        // Validate productName column
        Column productName = OrderItem.class.getDeclaredField("productName").getAnnotation(Column.class);

        Assertions.assertThat(productName).isNotNull();
        Assertions.assertThat(productName.nullable()).isFalse();
        Assertions.assertThat(productName.length()).isEqualTo(200);

        // Validate productSku column
        Column productSku = OrderItem.class.getDeclaredField("productSku").getAnnotation(Column.class);

        Assertions.assertThat(productSku).isNotNull();
        Assertions.assertThat(productSku.nullable()).isFalse();
        Assertions.assertThat(productSku.length()).isEqualTo(100);

        // Validate quantity column
        Column quantity = OrderItem.class.getDeclaredField("quantity").getAnnotation(Column.class);

        Assertions.assertThat(quantity).isNotNull();
        Assertions.assertThat(quantity.nullable()).isFalse();

        // Validate unitPrice column
        Column unitPrice = OrderItem.class.getDeclaredField("unitPrice").getAnnotation(Column.class);

        Assertions.assertThat(unitPrice).isNotNull();
        Assertions.assertThat(unitPrice.nullable()).isFalse();
        Assertions.assertThat(unitPrice.precision()).isEqualTo(10);
        Assertions.assertThat(unitPrice.scale()).isEqualTo(2);
    }

    /**
     * Tests OrderItem entity auditing field configuration.
     *
     * <p>
     * Verifies that the {@link OrderItem} entity defines the required auditing
     * fields with appropriate annotations and correct field types.
     * </p>
     */
    @Test
    void testForAuditFields() throws Exception {

        // Verify total auditing fields
        long auditFieldCount = Arrays.stream(OrderItem.class.getDeclaredFields())
                .filter(field -> field.isAnnotationPresent(CreationTimestamp.class)
                        || field.isAnnotationPresent(UpdateTimestamp.class)
                        || field.isAnnotationPresent(CreatedBy.class)
                        || field.isAnnotationPresent(LastModifiedBy.class))
                .count();

        Assertions.assertThat(auditFieldCount).as("OrderItem entity should have exactly 4 auditing fields")
                .isEqualTo(4);

        // createdDateTime
        Field createdDateTime = OrderItem.class.getDeclaredField("createdDateTime");
        Assertions.assertThat(createdDateTime.isAnnotationPresent(CreationTimestamp.class)).isTrue();
        Assertions.assertThat(createdDateTime.getType()).isEqualTo(LocalDateTime.class);

        // lastModifiedDateTime
        Field lastModifiedDateTime = OrderItem.class.getDeclaredField("lastModifiedDateTime");
        Assertions.assertThat(lastModifiedDateTime.isAnnotationPresent(UpdateTimestamp.class)).isTrue();
        Assertions.assertThat(lastModifiedDateTime.getType()).isEqualTo(LocalDateTime.class);

        // createdBy
        Field createdBy = OrderItem.class.getDeclaredField("createdBy");
        Assertions.assertThat(createdBy.isAnnotationPresent(CreatedBy.class)).isTrue();
        Assertions.assertThat(createdBy.getType()).isEqualTo(UUID.class);

        // modifiedBy
        Field modifiedBy = OrderItem.class.getDeclaredField("modifiedBy");
        Assertions.assertThat(modifiedBy.isAnnotationPresent(LastModifiedBy.class)).isTrue();
        Assertions.assertThat(modifiedBy.getType()).isEqualTo(UUID.class);
    }

    /**
     * Tests OrderItem entity many-to-one relationship configuration.
     *
     * <p>
     * Verifies that the {@link OrderItem} entity defines a correctly configured
     * {@link ManyToOne} relationship with {@link Order}, including join column
     * configuration and nullability constraints.
     * </p>
     */
    @Test
    void testForOrderManyToOneMapping() throws Exception {

        // Verify exactly one @ManyToOne relationship
        long manyToOneCount = Arrays.stream(OrderItem.class.getDeclaredFields())
                .filter(field -> field.isAnnotationPresent(ManyToOne.class)).count();

        Assertions.assertThat(manyToOneCount).as("OrderItem entity should have exactly one @ManyToOne relationship")
                .isEqualTo(1);

        // Retrieve order field
        Field orderField = OrderItem.class.getDeclaredField("order");

        // Verify @ManyToOne
        Assertions.assertThat(orderField.isAnnotationPresent(ManyToOne.class))
                .as("order field should be annotated with @ManyToOne").isTrue();

        // Verify @JoinColumn
        JoinColumn joinColumn = orderField.getAnnotation(JoinColumn.class);

        Assertions.assertThat(joinColumn).isNotNull();
        Assertions.assertThat(joinColumn.name()).isEqualTo("order_id");
        Assertions.assertThat(joinColumn.nullable()).isFalse();
    }
}
