package ai.agilery.order.entity;

import java.util.UUID;

import java.lang.reflect.Field;
import java.time.LocalDateTime;
import java.util.Arrays;

import org.assertj.core.api.Assertions;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;
import org.junit.jupiter.api.Test;
import org.springframework.data.annotation.CreatedBy;
import org.springframework.data.annotation.LastModifiedBy;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.OneToMany;
import jakarta.persistence.Table;

class OrderEntityTest {

    /**
     * Tests Order entity annotations and table index configuration.
     *
     * <p>
     * Verifies that the {@link Order} entity is correctly annotated with
     * {@link Entity} and {@link Table}, that Lombok {@code @Data} generates working
     * accessors, and that required database indexes are defined on the mapped
     * table.
     * </p>
     */
    @Test
    void testForAnnotationsAndTableIndexes() {

        // Verify @Entity
        Assertions.assertThat(Order.class).as("Order class should be annotated with @Entity")
                .hasAnnotation(Entity.class);

        // Verify Lombok @Data
        Order order = new Order();
        order.setCustomerName("John");

        Assertions.assertThat(order.getCustomerName())
                .as("Getter and setter generated by Lombok @Data should work correctly").isEqualTo("John");

        // Verify @Table
        Table table = Order.class.getAnnotation(Table.class);

        Assertions.assertThat(table).as("@Table annotation should be present on Order entity").isNotNull();

        Assertions.assertThat(table.name()).as("Database table name should be 'orders'").isEqualTo("orders");

        // Verify table indexes
        Index[] indexes = table.indexes();

        Assertions.assertThat(indexes).as("Order table should define exactly 2 indexes").hasSize(2);

        // Verify index on customerEmail column
        Assertions.assertThat(indexes).as("Index 'idx_order_customer_email' should exist on customerEmail column")
                .anySatisfy(index -> {
                    Assertions.assertThat(index.name()).isEqualTo("idx_order_customer_email");
                    Assertions.assertThat(index.columnList()).isEqualTo("customerEmail");
                });

        // index on orderStatus column
        Assertions.assertThat(indexes).as("Index 'idx_order_order_status' should exist on orderStatus column")
                .anySatisfy(index -> {
                    Assertions.assertThat(index.name()).isEqualTo("idx_order_order_status");
                    Assertions.assertThat(index.columnList()).isEqualTo("orderStatus");
                });
    }

    /**
     * Tests Order entity primary key field annotations.
     *
     * <p>
     * Verifies that the {@link Order} entity defines an {@code id} field annotated
     * with {@link Id} and {@link GeneratedValue}, and that the identifier
     * generation strategy is configured as {@link GenerationType.UUID}.
     * </p>
     */
    @Test
    void testForIdFieldAnnotations() throws Exception {

        // Retrieve the id field to validate primary key annotations
        Field idField = Order.class.getDeclaredField("id");

        // Verify id field is marked as primary key
        Assertions.assertThat(idField.isAnnotationPresent(Id.class)).as("Order should have @Id on id field").isTrue();

        // Verify id value is auto-generated
        Assertions.assertThat(idField.isAnnotationPresent(GeneratedValue.class)).as("Order id should be auto-generated")
                .isTrue();

        // Verify ID generation strategy is IDENTITY
        GeneratedValue generatedValue = idField.getAnnotation(GeneratedValue.class);
        Assertions.assertThat(generatedValue.strategy()).as("ID generation strategy should be IDENTITY")
                .isEqualTo(GenerationType.UUID);
    }

    /**
     * Tests Order entity column mappings and constraints.
     *
     * <p>
     * Verifies that the {@link Order} entity defines the expected {@link Column}
     * mappings with correct nullability, length, precision, and scale, and that
     * enum fields are persisted using {@link EnumType#STRING}.
     * </p>
     */
    @Test
    void testForColumnMappings() throws Exception {

        // Verify total number of fields annotated with @Column
        long columnCount = Arrays.stream(Order.class.getDeclaredFields())
                .filter(field -> field.isAnnotationPresent(Column.class)).count();

        Assertions.assertThat(columnCount).as("Order entity should have exactly 7 @Column fields").isEqualTo(7);

        // Validate customerName column constraints
        Column customerName = Order.class.getDeclaredField("customerName").getAnnotation(Column.class);
        Assertions.assertThat(customerName).isNotNull();
        Assertions.assertThat(customerName.nullable()).isFalse();
        Assertions.assertThat(customerName.length()).isEqualTo(200);

        // Validate customerEmail column constraints
        Column customerEmail = Order.class.getDeclaredField("customerEmail").getAnnotation(Column.class);
        Assertions.assertThat(customerEmail).isNotNull();
        Assertions.assertThat(customerEmail.nullable()).isFalse();
        Assertions.assertThat(customerEmail.length()).isEqualTo(200);

        // Validate deliveryAddress column constraints
        Column deliveryAddress = Order.class.getDeclaredField("deliveryAddress").getAnnotation(Column.class);
        Assertions.assertThat(deliveryAddress).isNotNull();
        Assertions.assertThat(deliveryAddress.nullable()).isFalse();
        Assertions.assertThat(deliveryAddress.length()).isEqualTo(500);

        // Validate orderStatus column and enum mapping
        Field orderStatusField = Order.class.getDeclaredField("orderStatus");
        Column orderStatus = orderStatusField.getAnnotation(Column.class);
        Assertions.assertThat(orderStatus).isNotNull();
        Assertions.assertThat(orderStatus.nullable()).isFalse();
        Assertions.assertThat(orderStatus.length()).isEqualTo(20);

        Enumerated orderStatusEnum = orderStatusField.getAnnotation(Enumerated.class);
        Assertions.assertThat(orderStatusEnum).isNotNull();
        Assertions.assertThat(orderStatusEnum.value()).isEqualTo(EnumType.STRING);

        // Validate totalAmount column precision and scale
        Column totalAmount = Order.class.getDeclaredField("totalAmount").getAnnotation(Column.class);
        Assertions.assertThat(totalAmount).isNotNull();
        Assertions.assertThat(totalAmount.nullable()).isFalse();
        Assertions.assertThat(totalAmount.precision()).isEqualTo(10);
        Assertions.assertThat(totalAmount.scale()).isEqualTo(2);

        // Validate paymentMethod column and enum mapping
        Field paymentMethodField = Order.class.getDeclaredField("paymentMethod");
        Column paymentMethod = paymentMethodField.getAnnotation(Column.class);
        Assertions.assertThat(paymentMethod).isNotNull();
        Assertions.assertThat(paymentMethod.nullable()).isFalse();
        Assertions.assertThat(paymentMethod.length()).isEqualTo(20);

        Enumerated paymentMethodEnum = paymentMethodField.getAnnotation(Enumerated.class);
        Assertions.assertThat(paymentMethodEnum).isNotNull();
        Assertions.assertThat(paymentMethodEnum.value()).isEqualTo(EnumType.STRING);

        // Validate notes column constraints
        Column notes = Order.class.getDeclaredField("notes").getAnnotation(Column.class);
        Assertions.assertThat(notes).isNotNull();
        Assertions.assertThat(notes.length()).isEqualTo(1000);
    }

    /**
     * Tests Order entity auditing field configuration.
     *
     * <p>
     * Verifies that the {@link Order} entity defines the required auditing fields
     * with appropriate annotations for creation time, modification time, and
     * auditor information, and that the field types are correctly configured.
     * </p>
     */
    @Test
    void testForAuditFields() throws Exception {

        // Verify total number of auditing-related fields
        long auditFieldCount = Arrays.stream(Order.class.getDeclaredFields())
                .filter(field -> field.isAnnotationPresent(CreationTimestamp.class)
                        || field.isAnnotationPresent(UpdateTimestamp.class)
                        || field.isAnnotationPresent(CreatedBy.class)
                        || field.isAnnotationPresent(LastModifiedBy.class))
                .count();

        Assertions.assertThat(auditFieldCount).as("Order entity should have exactly 4 auditing fields").isEqualTo(4);

        // Validate createdDateTime auditing configuration
        Field createdDateTime = Order.class.getDeclaredField("createdDateTime");
        Assertions.assertThat(createdDateTime.isAnnotationPresent(CreationTimestamp.class))
                .as("createdDateTime should have @CreationTimestamp").isTrue();
        Assertions.assertThat(createdDateTime.getType()).isEqualTo(LocalDateTime.class);

        // Validate lastModifiedDateTime auditing configuration
        Field lastModifiedDateTime = Order.class.getDeclaredField("lastModifiedDateTime");
        Assertions.assertThat(lastModifiedDateTime.isAnnotationPresent(UpdateTimestamp.class))
                .as("lastModifiedDateTime should have @UpdateTimestamp").isTrue();
        Assertions.assertThat(lastModifiedDateTime.getType()).isEqualTo(LocalDateTime.class);

        // Validate createdBy auditing configuration
        Field createdBy = Order.class.getDeclaredField("createdBy");
        Assertions.assertThat(createdBy.isAnnotationPresent(CreatedBy.class)).as("createdBy should have @CreatedBy")
                .isTrue();
        Assertions.assertThat(createdBy.getType()).isEqualTo(UUID.class);

        // Validate modifiedBy auditing configuration
        Field modifiedBy = Order.class.getDeclaredField("modifiedBy");
        Assertions.assertThat(modifiedBy.isAnnotationPresent(LastModifiedBy.class))
                .as("modifiedBy should have @LastModifiedBy").isTrue();
        Assertions.assertThat(modifiedBy.getType()).isEqualTo(UUID.class);
    }

    /**
     * Tests Order entity one-to-many relationship configuration.
     *
     * <p>
     * Verifies that the {@link Order} entity defines a correctly configured
     * {@link OneToMany} relationship with its order items, including proper
     * mapping, cascade behavior, orphan removal, and collection initialization.
     * </p>
     */
    @Test
    void testForOrderItemsOneToManyMapping() throws Exception {

        // Verify total number of @OneToMany relationships in Order entity
        long oneToManyCount = Arrays.stream(Order.class.getDeclaredFields())
                .filter(field -> field.isAnnotationPresent(OneToMany.class)).count();

        Assertions.assertThat(oneToManyCount).as("Order entity should have exactly one @OneToMany relationship")
                .isEqualTo(1);

        // Retrieve orderItems field for relationship validation
        Field orderItemsField = Order.class.getDeclaredField("orderItems");

        // Verify @OneToMany annotation is present on orderItems
        OneToMany oneToMany = orderItemsField.getAnnotation(OneToMany.class);
        Assertions.assertThat(oneToMany).as("orderItems should be annotated with @OneToMany").isNotNull();

        // Verify mappedBy configuration for bidirectional relationship
        Assertions.assertThat(oneToMany.mappedBy()).as("orderItems should be mapped by 'order' field in OrderItem")
                .isEqualTo("order");

        // Verify cascade configuration for orderItems
        Assertions.assertThat(oneToMany.cascade()).as("CascadeType.ALL should be configured for orderItems")
                .containsExactly(CascadeType.ALL);

        // Verify orphan removal is enabled
        Assertions.assertThat(oneToMany.orphanRemoval()).as("orphanRemoval should be enabled for orderItems").isTrue();

        // Verify orderItems collection is initialized by default
        Order order = new Order();
        Assertions.assertThat(order.getOrderItems()).as("orderItems collection should be initialized").isNotNull()
                .isEmpty();
    }

}
