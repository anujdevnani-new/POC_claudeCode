package ai.agilery.order.dto;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonProperty.Access;

import ai.agilery.order.enumeration.ValueOfEnum;
import ai.agilery.order.validation.NullOrNotEmpty;
import ai.agilery.order.validation.OnCreate;
import ai.agilery.order.validation.OnPatch;
import ai.agilery.order.validation.OnUpdate;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.Valid;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * Data Transfer Object for an Order.
 * Represents a customer order with all its details and associated order items.
 */
@Data
@Schema(description = "Details of a customer order, including customer information, status, and items.")
@AllArgsConstructor
@NoArgsConstructor
public class OrderDto {

    /**
     * Length 2.
     */
    private static final int LEN_2 = 2;

    /**
     * Length 10.
     */
    private static final int LEN_10 = 10;

    /**
     * Length 200.
     */
    private static final int LEN_200 = 200;

    /**
     * Length 255.
     */
    private static final int LEN_255 = 255;

    /**
     * Length 500.
     */
    private static final int LEN_500 = 500;

    /**
     * Length 1000.
     */
    private static final int LEN_1000 = 1000;

    /**
     * Unique identifier for the order.
     * This field is read-only and generated by the system.
     */
    @JsonProperty(access = Access.READ_ONLY)
    @Schema(description = "Unique identifier for the order.", accessMode = Schema.AccessMode.READ_ONLY, example = "123")
    private UUID id;

    /**
     * The name of the customer placing the order.
     * Required for creation and update, must be between 2 and 200 characters.
     */
    @Schema(description = "The name of the customer.", example = "John Doe")
    @NotBlank(groups = {OnCreate.class, OnUpdate.class})
    @NullOrNotEmpty(groups = OnPatch.class)
    @Size(min = LEN_2, max = LEN_200, groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Customer name must be between 2 and 200 characters")
    private String customerName;

    /**
     * The email address of the customer.
     * Required for creation and update, must be a valid email format.
     */
    @Schema(description = "The email address of the customer.", example = "john.doe@example.com")
    @NotBlank(groups = {OnCreate.class, OnUpdate.class})
    @NullOrNotEmpty(groups = OnPatch.class)
    @Email(groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Customer email must be a valid email address")
    @Size(max = LEN_255, groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Customer email cannot exceed 255 characters")
    private String customerEmail;

    /**
     * The delivery address for the order.
     * Required for creation and update, must be between 10 and 500 characters.
     */
    @Schema(description = "The delivery address for the order.", example = "123 Main St, Anytown, USA")
    @NotBlank(groups = {OnCreate.class, OnUpdate.class})
    @NullOrNotEmpty(groups = OnPatch.class)
    @Size(min = LEN_10, max = LEN_500, groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Delivery address must be between 10 and 500 characters")
    private String deliveryAddress;

    /**
     * The current status of the order.
     * Required for creation and update, must be one of the defined OrderStatus enum values.
     */
    @Schema(description = "The current status of the order.", example = "PENDING")
    @NotNull(groups = {OnCreate.class, OnUpdate.class})
    @ValueOfEnum(enumClass = OrderStatus.class, groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Invalid order status")
    @NullOrNotEmpty(groups = OnPatch.class) // NullOrNotEmpty is for String fields, not enums. This should be removed or replaced if enum is optional on patch.
    private String orderStatus;

    /**
     * The total amount of the order. It is a derived field from order items.
     */
    @Schema(description = "The total amount of the order.", accessMode = Schema.AccessMode.READ_ONLY)
    private BigDecimal totalAmount;

    /**
     * The payment method used for the order.
     * Required for creation and update, must be one of the defined PaymentMethod enum values.
     */
    @Schema(description = "The payment method used for the order.", example = "CREDIT_CARD")
    @NotNull(groups = {OnCreate.class, OnUpdate.class})
    @ValueOfEnum(enumClass = PaymentMethod.class, groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Invalid payment method")
    @NullOrNotEmpty(groups = OnPatch.class) // NullOrNotEmpty is for String fields, not enums. This should be removed or replaced if enum is optional on patch.
    private String paymentMethod;

    /**
     * Optional notes or special instructions for the order.
     * Maximum 1000 characters.
     */
    @Schema(description = "Optional notes or special instructions for the order.", example = "Deliver after 5 PM.")
    @NullOrNotEmpty(groups = OnPatch.class)
    @Size(max = LEN_1000, groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Notes cannot exceed 1000 characters")
    private String notes;

    /**
     * A list of items included in this order.
     * Required for creation, must not be empty, and each item must be valid.
     */
    @Schema(description = "A list of items included in this order.")
    @NotEmpty(groups = OnCreate.class, message = "Order must contain at least one item")
    @Valid // Ensures nested validation for each OrderItemDto
    private List<OrderItemDto> orderItems;

    /**
     * The date and time when the order was created.
     * This field is read-only and automatically set by the system.
     */
    @JsonProperty(access = Access.READ_ONLY)
    @Schema(description = "Timestamp when the order was created.", accessMode = Schema.AccessMode.READ_ONLY)
    private LocalDateTime createdDateTime;

    /**
     * The date and time when the order was last modified.
     * This field is read-only and automatically updated by the system.
     */
    @JsonProperty(access = Access.READ_ONLY)
    @Schema(description = "Timestamp when the order was last modified.", accessMode = Schema.AccessMode.READ_ONLY)
    private LocalDateTime lastModifiedDateTime;

    /**
     * The ID of the user who created this order.
     * This field is read-only and automatically set by the system.
     */
    @JsonProperty(access = Access.READ_ONLY)
    @Schema(description = "ID of the user who created this order.", accessMode = Schema.AccessMode.READ_ONLY)
    private UUID createdBy;

    /**
     * The ID of the user who last modified this order.
     * This field is read-only and automatically updated by the system.
     */
    @JsonProperty(access = Access.READ_ONLY)
    @Schema(description = "ID of the user who last modified this order.", accessMode = Schema.AccessMode.READ_ONLY)
    private UUID modifiedBy;
}
