package ai.agilery.order.entity;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.UUID;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;
import org.springframework.data.annotation.CreatedBy;
import org.springframework.data.annotation.LastModifiedBy;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Data;

/**
 * Entity representing an individual item within an order.
 * Maps to the {@code order_items} table in the database.
 * Each order item is associated with a specific order and contains details about the product, quantity, and price.
 */
@Data
@Entity
@Table(name = "order_items", indexes = {
        @Index(name = "idx_order_item_order_id", columnList = "order_id"),
        @Index(name = "idx_order_item_product_sku", columnList = "product_sku")
})
public class OrderItem {

    /**
     * Length 2.
     */
    private static final int LEN_2 = 2;

    /**
     * Length 10.
     */
    private static final int LEN_10 = 10;
    /**
     * Length 100.
     */
    private static final int LEN_100 = 100;
    /**
     * Length 200.
     */
    private static final int LEN_200 = 200;

    /**
     * Unique identifier for the order item. Auto-generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /**
     * The order to which this item belongs.
     * Establishes a many-to-one relationship with {@link Order}.
     * The foreign key column is `order_id` and it cannot be null.
     */
    @ManyToOne
    @JoinColumn(name = "order_id", nullable = false)
    private Order order;

    /**
     * Name of the product in this order item.
     * Required field with a maximum length of 200 characters.
     */
    @Column(nullable = false, length = LEN_200)
    private String productName;

    /**
     * Stock Keeping Unit (SKU) of the product.
     * Required field with a maximum length of 100 characters.
     */
    @Column(nullable = false, length = LEN_100)
    private String productSku;

    /**
     * Quantity of the product ordered.
     * Required field and must be a positive integer.
     */
    @Column(nullable = false)
    private Integer quantity;

    /**
     * Unit price of the product.
     * Required field with a precision of 10 digits and 2 decimal places.
     */
    @Column(nullable = false, precision = LEN_10, scale = LEN_2)
    private BigDecimal unitPrice;

    /**
     * Timestamp when the entity was created.
     * Automatically set upon creation.
     */
    @CreationTimestamp
    private LocalDateTime createdDateTime;

    /**
     * Timestamp when the entity was last modified.
     * Automatically updated on each modification.
     */
    @UpdateTimestamp
    private LocalDateTime lastModifiedDateTime;

    /**
     * ID of the user who created this entity.
     * Populated by Spring Data JPA auditing.
     */
    @CreatedBy
    private UUID createdBy;

    /**
     * ID of the user who last modified this entity.
     * Populated by Spring Data JPA auditing.
     */
    @LastModifiedBy
    private UUID modifiedBy;
}
