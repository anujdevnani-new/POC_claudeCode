package ai.agilery.order.dto;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.UUID;

import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonProperty.Access;

import ai.agilery.order.validation.NullOrNotEmpty; // Corrected import
import ai.agilery.order.validation.OnCreate; // Corrected import
import ai.agilery.order.validation.OnPatch; // Corrected import
import ai.agilery.order.validation.OnUpdate; // Corrected import
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * Data Transfer Object for an Order Item.
 * Represents a single product within an order, including details like product name, SKU, quantity, and price.
 */
@Data
@Schema(description = "Details of a single item within an order.")
@AllArgsConstructor
@NoArgsConstructor
public class OrderItemDto {

    /**
     * Length 1.
     */
    private static final int LEN_1 = 1;

    /**
     * Length 2.
     */
    private static final int LEN_2 = 2;

    /**
     * Length 100.
     */
    private static final int LEN_100 = 100;

    /**
     * Length 200.
     */
    private static final int LEN_200 = 200;

    /**
     * Unique identifier for the order item.
     * This field is read-only and generated by the system.
     */
    @JsonProperty(access = Access.READ_ONLY)
    @Schema(description = "Unique identifier for the order item.", accessMode = Schema.AccessMode.READ_ONLY)
    private UUID id;

    /**
     * The name of the product.
     * Required for creation and update, must be between 2 and 200 characters.
     */
    @Schema(description = "The name of the product.", example = "Laptop Pro X")
    @NotBlank(groups = {OnCreate.class, OnUpdate.class})
    @NullOrNotEmpty(groups = OnPatch.class)
    @Size(min = LEN_2, max = LEN_200, groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Product name must be between 2 and 200 characters")
    private String productName;

    /**
     * The Stock Keeping Unit (SKU) of the product.
     * Required for creation and update, must be between 2 and 100 characters.
     */
    @Schema(description = "The Stock Keeping Unit (SKU) of the product.", example = "LPX-2023-001")
    @NotBlank(groups = {OnCreate.class, OnUpdate.class})
    @NullOrNotEmpty(groups = OnPatch.class)
    @Size(min = LEN_2, max = LEN_100, groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Product SKU must be between 2 and 100 characters")
    private String productSku;

    /**
     * The quantity of the product ordered.
     * Required for creation and update, must be a positive integer with a minimum value of 1.
     */
    @Schema(description = "The quantity of the product ordered.", example = "2")
    @NotNull(groups = {OnCreate.class, OnUpdate.class})
    @Min(value = LEN_1, groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Quantity must be at least 1")
    @Positive(groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Quantity must be positive")
    private Integer quantity;

    /**
     * The unit price of the product.
     * Required for creation and update, must be a positive decimal value.
     */
    @Schema(description = "The unit price of the product.", example = "1200.00")
    @NotNull(groups = {OnCreate.class, OnUpdate.class})
    @Positive(groups = {OnCreate.class, OnUpdate.class, OnPatch.class}, message = "Unit price must be positive")
    private BigDecimal unitPrice;

    /**
     * The date and time when the order item was created.
     * This field is read-only and automatically set by the system.
     */
    @JsonProperty(access = Access.READ_ONLY)
    @Schema(description = "Timestamp when the order item was created.", accessMode = Schema.AccessMode.READ_ONLY)
    private LocalDateTime createdDateTime;

    /**
     * The date and time when the order item was last modified.
     * This field is read-only and automatically updated by the system.
     */
    @JsonProperty(access = Access.READ_ONLY)
    @Schema(description = "Timestamp when the order item was last modified.", accessMode = Schema.AccessMode.READ_ONLY)
    private LocalDateTime lastModifiedDateTime;

    /**
     * The ID of the user who created this order item.
     * This field is read-only and automatically set by the system.
     */
    @JsonProperty(access = Access.READ_ONLY)
    @Schema(description = "ID of the user who created this order item.", accessMode = Schema.AccessMode.READ_ONLY)
    private UUID createdBy;

    /**
     * The ID of the user who last modified this order item.
     * This field is read-only and automatically updated by the system.
     */
    @JsonProperty(access = Access.READ_ONLY)
    @Schema(description = "ID of the user who last modified this order item.", accessMode = Schema.AccessMode.READ_ONLY)
    private UUID modifiedBy;
}
