package ai.agilery.order.entity;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;
import org.springframework.data.annotation.CreatedBy;
import org.springframework.data.annotation.LastModifiedBy;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.OneToMany;
import jakarta.persistence.Table;
import lombok.Data;

/**
 * Entity representing an order in the order management system.
 * Maps to the {@code orders} table in the database.
 * Contains details about the customer, delivery, status, payment, and associated order items.
 */
@Data
@Entity
@Table(name = "orders", indexes = {
        @Index(name = "idx_order_customer_email", columnList = "customerEmail"),
        @Index(name = "idx_order_order_status", columnList = "orderStatus")
})
public class Order {

    /**
     * Length 2.
     */
    private static final int LEN_2 = 2;

    /**
     * Length 10.
     */
    private static final int LEN_10 = 10;

    /**
     * Length 20.
     */
    private static final int LEN_20 = 20;

    /**
     * Length 200.
     */
    private static final int LEN_200 = 200;

    /**
     * Length 500.
     */
    private static final int LEN_500 = 500;

    /**
     * Length 1000.
     */
    private static final int LEN_1000 = 1000;

    /**
     * Unique identifier for the order. Auto-generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /**
     * Name of the customer who placed the order.
     * Required field with a maximum length of 200 characters.
     */
    @Column(nullable = false, length = LEN_200)
    private String customerName;

    /**
     * Email address of the customer.
     * Required field with a maximum length of 200 characters.
     */
    @Column(nullable = false, length = LEN_200)
    private String customerEmail;

    /**
     * Delivery address for the order.
     * Required field with a maximum length of 500 characters.
     */
    @Column(nullable = false, length = LEN_500)
    private String deliveryAddress;

    /**
     * Current status of the order (e.g., PENDING, CONFIRMED, SHIPPED).
     * Stored as a string in the database and cannot be null.
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = LEN_20)
    private OrderStatus orderStatus;

    /**
     * Total monetary amount of the order.
     * Required field with a precision of 10 digits and 2 decimal places.
     */
    @Column(nullable = false, precision = LEN_10, scale = LEN_2)
    private BigDecimal totalAmount;

    /**
     * Method used for payment (e.g., CREDIT_CARD, DEBIT_CARD, CASH, UPI).
     * Stored as a string in the database and cannot be null.
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = LEN_20)
    private PaymentMethod paymentMethod;

    /**
     * Optional notes or special instructions for the order.
     * Maximum length of 1000 characters.
     */
    @Column(length = LEN_1000)
    private String notes;

    /**
     * List of items included in this order.
     * Establishes a one-to-many relationship with {@link OrderItem}.
     * CascadeType.ALL ensures that all operations (persist, merge, remove) are cascaded to associated order items.
     * orphanRemoval = true ensures that if an OrderItem is removed from the collection, it is deleted from the database.
     */
    @OneToMany(mappedBy = "order", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<OrderItem> orderItems = new ArrayList<>();

    /**
     * Timestamp when the entity was created.
     * Automatically set upon creation.
     */
    @CreationTimestamp
    private LocalDateTime createdDateTime;

    /**
     * Timestamp when the entity was last modified.
     * Automatically updated on each modification.
     */
    @UpdateTimestamp
    private LocalDateTime lastModifiedDateTime;

    /**
     * ID of the user who created this entity.
     * Populated by Spring Data JPA auditing.
     */
    @CreatedBy
    private UUID createdBy;

    /**
     * ID of the user who last modified this entity.
     * Populated by Spring Data JPA auditing.
     */
    @LastModifiedBy
    private UUID modifiedBy;
}
